"""Render a saved eval run as Markdown for the README.

The README's benchmark section sits between marker comments and is *generated*
from ``eval/results`` by ``scripts/benchmark_table.py --write``, so every number
in it traces back to a real run on a recorded machine.
"""

from __future__ import annotations

import re
from typing import Any

START = "<!-- BENCHMARK:START -->"
END = "<!-- BENCHMARK:END -->"


def _pct(v: Any) -> str:
    return f"{v * 100:.0f}%" if isinstance(v, int | float) else "–"


def _num(v: Any, fmt: str = ".1f") -> str:
    return format(v, fmt) if isinstance(v, int | float) else "–"


def render_benchmark(run: dict[str, Any]) -> str:
    meta, summary = run["meta"], run["summary"]
    hw = meta.get("hardware", {})
    categories = sorted(
        k.removeprefix("correctness_") for k in summary[0] if k.startswith("correctness_")
    )
    lines = [
        f"_Run `{meta['run_id']}` · {meta['dataset']['examples']} prompts "
        f"(`{meta['dataset']['name']}`) · judge `{meta['judge_model']}` · "
        f"temperature {meta['params']['temperature']} · generated by "
        "`scripts/benchmark_table.py`._",
        "",
        "**Quality**",
        "",
        "| Model | Correctness | "
        + " | ".join(c.capitalize() for c in categories)
        + " | Conciseness | Refusal acc. | Unsafe | Over-refusals |",
        "|---|---|" + "---|" * len(categories) + "---|---|---|---|",
    ]
    for r in summary:
        cats = " | ".join(_pct(r.get(f"correctness_{c}")) for c in categories)
        lines.append(
            f"| `{r['model']}` | **{_pct(r['correctness'])}** | {cats} | {_pct(r['conciseness'])} "
            f"| {_pct(r['refusal_accuracy'])} | {r['unsafe_answers']} | {r['over_refusals']} |"
        )
    lines += [
        "",
        "**Speed** (one request at a time, warm model)",
        "",
        "| Model | Avg latency | Median latency | Time to first token | Tokens/sec |",
        "|---|---|---|---|---|",
    ]
    for r in summary:
        lines.append(
            f"| `{r['model']}` | {_num(r['avg_latency_s'], '.2f')} s | "
            f"{_num(r['p50_latency_s'], '.2f')} s | {_num(r['avg_ttft_ms'], '.0f')} ms | "
            f"{_num(r['avg_tokens_per_sec'])} |"
        )
    ram = f"{hw['ram_gb']} GB" if hw.get("ram_gb") else "unknown"
    lines += [
        "",
        "**Hardware**",
        "",
        "| | |",
        "|---|---|",
        f"| CPU | {hw.get('cpu', 'unknown')} ({hw.get('cpu_cores', '?')} cores) |",
        f"| RAM | {ram} |",
        f"| GPU | {hw.get('gpu') or 'none detected (CPU inference)'} |",
        f"| OS | {hw.get('os', 'unknown')} ({hw.get('machine', '')}) |",
        f"| Ollama | {meta.get('ollama_version') or 'unknown'} |",
    ]
    if meta.get("comparison_url"):
        lines += ["", f"[Open the LangSmith experiment comparison]({meta['comparison_url']})"]
    return "\n".join(lines)


def replace_between_markers(document: str, content: str) -> str:
    """Swap the text between the BENCHMARK markers; raise if they're missing."""
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(document):
        raise ValueError(f"markers {START} ... {END} not found")
    return pattern.sub(lambda _: f"{START}\n{content}\n{END}", document, count=1)
